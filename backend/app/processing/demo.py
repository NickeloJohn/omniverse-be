"""Deterministic SYNTHETIC terrain for DEMO mode. Contains no NASA measurements.

Elevations are relative metres on an arbitrary datum. Features: gentle rolling terrain, a crater-like bowl,
a steep-sided mesa that can be walked around, and a rectangular unknown-data patch (NoData).
"""

import numpy as np

from app.processing.grid import TargetGrid

DEMO_SEED = 20_260_001
DEMO_GENERATOR_VERSION = "demo-terrain-v2"
DEMO_NOTE = "Synthetic DEMO terrain generated by MARS-NAV; not derived from any NASA product."
UNKNOWN_PATCH_M = (-1500.0, -1000.0, 1000.0, 1500.0)  # x_min, x_max, y_min, y_max


def _step(u: np.ndarray) -> np.ndarray:
    return 0.5 * (1.0 + np.tanh(u))


def generate_demo_elevation(grid: TargetGrid, seed: int = DEMO_SEED) -> np.ndarray:
    """float32 (rows, cols) elevation with NaN in the unknown patch."""
    rows, cols = np.indices(grid.shape)
    x = grid.bounds[0] + (cols + 0.5) * grid.resolution_m
    y = grid.bounds[3] - (rows + 0.5) * grid.resolution_m

    z = 60.0 * np.sin(x / 1100.0 + 0.6) * np.cos(y / 900.0 - 0.3)
    r2 = (x - 1500.0) ** 2 + (y - 1500.0) ** 2
    z -= 110.0 * np.exp(-r2 / 650.0**2)
    # Mesa x 1800..3600, y > -800: steep on all sides, so it is a barrier with open ground around it.
    z += 55.0 * _step((x - 1800.0) / 60.0) * _step((3600.0 - x) / 60.0) * _step((y + 800.0) / 60.0)

    noise = np.random.default_rng(seed).normal(0.0, 0.15, size=grid.shape)
    z = (z + noise).astype(np.float32)

    x0, x1, y0, y1 = UNKNOWN_PATCH_M
    z[(x >= x0) & (x <= x1) & (y >= y0) & (y <= y1)] = np.nan
    return z
